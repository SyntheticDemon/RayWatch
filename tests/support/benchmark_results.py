"""Write merged jobs-list latency report (always updated on perf / benchmark runs)."""

from __future__ import annotations

import re
from datetime import UTC, datetime
from pathlib import Path

REPORT_PATH = Path(__file__).resolve().parents[2] / "benchmark-results" / "jobs-list-latency.md"

SECTION_PERF = "## RayWatch read-path regression (`make perf`)"
SECTION_RAY_COMPARE = "## RayWatch vs Ray dashboard (`make benchmark`)"


def _now_iso() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")


def _read_sections() -> dict[str, str]:
    if not REPORT_PATH.is_file():
        return {}
    text = REPORT_PATH.read_text(encoding="utf-8")
    sections: dict[str, str] = {}
    for title in (SECTION_PERF, SECTION_RAY_COMPARE):
        pattern = rf"({re.escape(title)}.*?)(?=\n## |\Z)"
        match = re.search(pattern, text, re.DOTALL)
        if match:
            sections[title] = match.group(1).strip()
    return sections


def write_jobs_list_latency_report(
    section_title: str,
    table_markdown: str,
    *,
    note: str = "",
) -> Path:
    """Merge one section into jobs-list-latency.md and write the file."""
    sections = _read_sections()
    body = f"{section_title}\n\n_Last updated: {_now_iso()}_\n\n"
    if note:
        body += f"{note}\n\n"
    body += table_markdown.strip() + "\n"
    sections[section_title] = body.strip()

    parts = [
        "# Jobs list latency",
        "",
        "Auto-generated by `make perf` and `make benchmark` / `make benchmark-ray`. Not a CI gate.",
        "",
    ]
    if SECTION_PERF in sections:
        parts.append(sections[SECTION_PERF])
        parts.append("")
    if SECTION_RAY_COMPARE in sections:
        parts.append(sections[SECTION_RAY_COMPARE])
        parts.append("")

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
    return REPORT_PATH
